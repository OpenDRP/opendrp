#!/usr/bin/env python3
"""Fail when a withdrawn provider reappears in the source or the documentation.

Censys Platform v3, FOFA and Criminal IP were withdrawn from the platform: their
connector sources, provider code, Compose services, settings, registry rows,
tests and public documentation were all removed, and Netlas stayed as the only
optional passive provider. Withdrawal is a property of the platform and not a
step in a deployment's history — the schema a fresh installation is created from
carries no row for them at all — so a name that survives in code or prose is the
only way they can come back.

Nothing joined the two halves of that decision, so names survived where no test
looked: the DNS Security page still offered Censys, FOFA and Criminal IP as
source filters, the Exposure page offered the same three plus Netlas while the
exposure module has exactly two providers, and ``docs/dns-security.md``
advertised "Censys (optional)" as a source. A filter entry that no connector can
produce is a control that only looks like one, and a page that lists a provider
the platform does not ship sends an operator looking for a token that does not
exist. Withdrawal is a property of the repository, and this gate is what makes it
one.

Deliberate exceptions, each with its reason in ``ALLOWED`` below: the tests that
assert their absence, the release note and the upgrade note that announce it, the
pages that document which providers remain, and this gate with its own test.
``docs/internal`` is skipped because it is deliberately outside the repository
(see ``check_tracked_sources.py``), and ``.env`` is skipped because a developer's
own secrets file is not source.

Usage: python scripts/check_withdrawn_providers.py [repo-root]

Exit codes: 0 clean, 1 an unallowed reference, 2 unreadable input.
"""

from __future__ import annotations

import re
import sys
from collections.abc import Iterator
from pathlib import Path

#: Word boundaries that treat ``_`` as a separator, so the environment-variable
#: spelling (``CENSYS_API_KEY``) is caught while an unrelated word that merely
#: contains the letters (``fofapro``) is not.
_REFERENCE = re.compile(
    r"(?i)(?<![a-z0-9])(censys|fofa|criminal[ _-]?ip)(?![a-z0-9])"
)

#: Directories whose contents are build output, caches or dependencies rather
#: than source. `frontend/dist` is the compiled bundle: it is excluded from the
#: repository on purpose and regenerated by a build.
_SKIP_DIRS = frozenset(
    {
        ".git",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        "build",
        "dist",
        "node_modules",
        "reports_store",
        "__pycache__",
    }
)

#: Trees that are ignored by ``.gitignore`` on purpose, so they are not part of
#: the repository this gate protects.
_IGNORED_TREES = (("docs", "internal"),)

#: Files that are not source even though they carry the names.
_SKIP_FILES = frozenset({".env"})

#: Suffixes that cannot be read as text and are not worth flagging.
_SKIP_SUFFIXES = frozenset(
    {
        ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip", ".gz", ".tar",
        ".whl", ".so", ".dylib", ".dll", ".pyc", ".woff", ".woff2", ".ttf",
        ".sqlite", ".sqlite3", ".db",
    }
)

#: Where a withdrawn name is correct, and why. Every entry must exist: a stale
#: exemption is how an allowlist quietly becomes an unenforced rule. No entry may
#: name a revision file — the rows are not seeded in the first place, so a
#: revision that mentions them would be the defect rather than the exception.
ALLOWED: dict[str, str] = {
    "backend/tests/test_alembic_migrations.py": (
        "a test that asserts they are absent has to name them"
    ),
    "backend/tests/test_exposure_endpoints_connector.py": (
        "uses a withdrawn provider as the unknown name a worker must reject"
    ),
    "CHANGELOG.md": "the release note that announces the removal",
    "docs/dns-security.md": "states which providers were withdrawn and stay withdrawn",
    "docs/source-intelligence.md": "documents that Netlas is the only optional provider",
    "docs/upgrading.md": (
        "states which providers a deployment has and which were withdrawn from it"
    ),
    "scripts/check_withdrawn_providers.py": "this gate names them to find them",
    "backend/tests/test_withdrawn_providers_gate.py": "the gate's own test",
}


def _iter_files(root: Path) -> Iterator[Path]:
    """Every text file under *root* that could carry a provider name."""
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(root)
        if any(part in _SKIP_DIRS for part in relative.parts):
            continue
        if any(relative.parts[: len(tree)] == tree for tree in _IGNORED_TREES):
            continue
        if path.name in _SKIP_FILES:
            continue
        if path.name.startswith(".env") and path.name != ".env.example":
            continue
        if path.suffix.lower() in _SKIP_SUFFIXES:
            continue
        yield path


def matches(text: str) -> list[str]:
    """The withdrawn provider names *text* mentions, lowercased and unique."""
    return sorted({match.group(1).lower() for match in _REFERENCE.finditer(text)})


def check(root: Path) -> list[str]:
    """Unallowed references, plus exemptions that no longer name a real file."""
    failures: list[str] = []

    for relative in sorted(ALLOWED):
        if not (root / relative).is_file():
            failures.append(
                f"{relative}: listed in ALLOWED but missing — remove the exemption "
                "or fix the path"
            )

    for path in _iter_files(root):
        # Relative, not absolute: the exemptions are repository-relative paths,
        # and a checkout can be scanned from anywhere.
        relative = path.relative_to(root).as_posix()
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError as exc:  # pragma: no cover - unreadable file
            failures.append(f"{relative}: cannot read ({exc})")
            continue
        names = matches(text)
        if not names:
            continue
        if relative in ALLOWED:
            continue
        for line_number, line in enumerate(text.splitlines(), start=1):
            for name in matches(line):
                failures.append(
                    f"{relative}:{line_number}: mentions withdrawn provider "
                    f"{name!r}: {line.strip()[:120]}"
                )

    return failures


def main(argv: list[str]) -> int:
    # `argv` includes the program name, as in the sibling gates, so a test can
    # call `main(["check_withdrawn_providers.py", root])`.
    args = argv[1:]
    if len(args) > 1:
        print("usage: python scripts/check_withdrawn_providers.py [repo-root]")
        return 2
    root = Path(args[0]) if args else Path(".")
    if not root.is_dir():
        print(f"withdrawn providers gate: FAILED — {root} is not a directory")
        return 2

    try:
        failures = check(root)
    except OSError as exc:
        print(f"withdrawn providers gate: FAILED — cannot scan {root}: {exc}")
        return 2

    if failures:
        print("withdrawn providers gate: FAILED")
        for failure in failures:
            print(f"  - {failure}")
        print(
            "\nCensys, FOFA and Criminal IP are not part of the platform. Remove the "
            "reference, or add the file to ALLOWED with the reason it is correct there."
        )
        return 1

    print(
        "withdrawn providers gate: OK — Censys, FOFA and Criminal IP appear only "
        f"in {len(ALLOWED)} documented place(s)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
